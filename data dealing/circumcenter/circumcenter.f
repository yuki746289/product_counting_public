     &         -y3*z2*y1**2-y4*z3*y1**2-y2*z4*y1**2
     &         -y1*z3*y2**2-y3*z4*y2**2-y4*z1*y2**2
     &         -y2*z1*y3**2-y4*z2*y3**2-y1*z4*y3**2
     &         -y1*z2*y4**2-y2*z3*y4**2-y3*z1*y4**2
     &         -y3*z2*z1**2-y4*z3*z1**2-y2*z4*z1**2
     &         -y1*z3*z2**2-y3*z4*z2**2-y4*z1*z2**2
     &         -y2*z1*z3**2-y4*z2*z3**2-y1*z4*z3**2
     &         -y1*z2*z4**2-y2*z3*z4**2-y3*z1*z4**2)
        x0=x0/xyz
c
        y0=4d0*(x4*z3*x1**2+x3*z2*x1**2+x2*z4*x1**2
     &         +x3*z4*x2**2+x4*z1*x2**2+x1*z3*x2**2
     &         +x2*z1*x3**2+x1*z4*x3**2+x4*z2*x3**2
     &         +x1*z2*x4**2+x2*z3*x4**2+x3*z1*x4**2
     &         +x1*z2*y4**2+x2*z3*y4**2+x3*z1*y4**2
     &         +x3*z4*y2**2+x4*z1*y2**2+x1*z3*y2**2
     &         +x2*z1*y3**2+x1*z4*y3**2+x4*z2*y3**2
     &         +x4*z3*y1**2+x3*z2*y1**2+x2*z4*y1**2
     &         +x3*z2*z1**2+x2*z4*z1**2+x4*z3*z1**2
     &         +x3*z4+z2**2+x4*z1*z2**2+x1*z3*z2**2
     &         +x2*z1*z3**2+x1*z4*z3**2+x4*z2*z3**2
