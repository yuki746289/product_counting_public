c
        xyz=8d0*(x1*y3*z4+x1*y4*z2+x1*y2*z3+x2*y1*z4+x2*y3*z1+x2*y4*z3
     &          +x3*y1*z2+x3*y4*z1+x3*y2*z4+x4*y1*z3+x4*y2*z1+x4*y3*z2
     &          -x1*y3*z2-x1*y2*z4-x1*y4*z3-x2*y3*z4-x2*y1*z3-x2*y4*z1
     &          -x3*y4*z2-x3*y1*z4-x3*y2*z1-x4*y2*z3-x4*y1*z2-x4*y3*z1)
