        return
        end



        subroutine circumct3(x1,y1,z1,x2,y2,z2
     &                       ,x3,y3,z3,x4,y4,z4,x0,y0,z0)
        implicit double precision(a-h,o-z)
c
        a1=2d0*(x1-x2)
        a2=2d0*(x1-x3)
        a3=2d0*(x1-x4)
        b1=2d0*(y1-y2)
        b2=2d0*(y1-y3)
        b3=2d0*(y1-y4)
        c1=2d0*(z1-z2)
        c2=2d0*(z1-z3)
        c3=2d0*(z1-z4)
        d1=x1**2-x2**2+y1**2-y2**2+z1**2-z2**2
        d2=x1**2-x3**2+y1**2-y3**2+z1**2-z3**2
        d3=x1**2-x4**2+y1**2-y4**2+z1**2-z4**2
c
        xyz=a1*b2*c3+a2*b3*c1+a3*b1*c2-a3*b2*c1-a2*b1*c3-a1*b3*c2
        x0=(b1*c2*d3+b2*c3*d1+b3*c1*d2-b3*c2*d1-b2*c1*d3-b1*c3*d2)/xyz
        y0=(a1*d2*c3+a2*d3*c1+a3*d1*c2-a3*d2*c1-a2*d1*c3-a1*d3*c2)/xyz
        z0=(a1*b2*d3+a2*b3*d1+a3*b1*d2-a3*b2*d1-a2*b1*d3-a1*b3*d2)/xyz
c
        return
        end
