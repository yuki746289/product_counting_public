     &         -x4*z3*z2**2-x3*z1*z2**2-x1*z4*z2**2)
        y0=y0/xyz
c
        z0=4d0*(x2*y3*x1**2+x3*y4*x1**2+x4*y2*x1**2
     &         +x4*y3*x2**2+x3*y1*x2**2+x1*y4*x2**2
